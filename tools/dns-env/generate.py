"""Write deploy/*/config/traefik/dns-providers.env from the DNS provider definitions.

Traefik reads DNS provider credentials only from its environment, fixed when the container is
created. This file declares every provider variable as NAME_FILE=/etc/traefik/secrets/name.secret,
so Traefik loads it once (Compose env_file) and Traefik Console only ever writes the secret files.

    python3 tools/dns-env/generate.py          # write the files
    python3 tools/dns-env/generate.py --check  # fail if they are out of date (CI)
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
PROVIDERS = ROOT / "backend/internal/core/resolvers/providers/providers.json"
TARGETS = [ROOT / f"deploy/{d}/config/traefik/dns-providers.env" for d in ("traefik-console", "traefik-console-crowdsec")]
SECRETS = "/etc/traefik/secrets"  # Traefik's secrets folder (TRAEFIK_SECRETS_DIR)


def env_vars(node):
    if isinstance(node, dict):
        if isinstance(node.get("env_var"), str):
            yield node["env_var"]
        for value in node.values():
            yield from env_vars(value)
    elif isinstance(node, list):
        for value in node:
            yield from env_vars(value)


def render():
    providers = json.loads(PROVIDERS.read_text())["providers"]
    lines = [
        "# DNS provider credentials for Traefik's certificate resolvers. Do not edit:",
        "# generated by tools/dns-env/generate.py from the provider list Traefik Console supports.",
        "#",
        "# Each line points a provider variable at a file in Traefik's secrets folder. Traefik Console",
        "# writes those files when you create or update a resolver, so Traefik never needs new",
        "# variables. Lines of providers you don't use are ignored.",
    ]
    for code in sorted(providers):
        name = providers[code].get("display_name", code)
        lines += ["", f"# {name}"]
        for var in sorted(set(env_vars(providers[code]))):
            lines.append(f"{var}_FILE={SECRETS}/{var.lower()}.secret")
    return "\n".join(lines) + "\n"


def main():
    content = render()
    if "--check" in sys.argv[1:]:
        stale = [str(t.relative_to(ROOT)) for t in TARGETS if not t.exists() or t.read_text() != content]
        if stale:
            sys.exit("out of date, run python3 tools/dns-env/generate.py: " + ", ".join(stale))
        print("dns-providers.env files are up to date")
        return
    for target in TARGETS:
        target.write_text(content)
        print("wrote", target.relative_to(ROOT))


if __name__ == "__main__":
    main()
