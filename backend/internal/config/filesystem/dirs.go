package filesystem

import (
	"fmt"
	"os"
)

func EnsureDir(path string) error {
	if e := os.MkdirAll(path, 0700); e != nil {
		return e
	}
	st, e := os.Lstat(path)
	if e != nil {
		return e
	}
	if !st.IsDir() || st.Mode()&os.ModeSymlink != 0 {
		return fmt.Errorf("directory must not be a symlink")
	}
	return nil
}
